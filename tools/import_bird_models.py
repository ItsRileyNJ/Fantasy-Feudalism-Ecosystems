"""Import the supplied untextured Blockbench cubes into native articulated bird layers."""
import json,math,hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCES=ROOT/'docs/model-sources/birds'
OUT=ROOT/'src/main/java/net/itsrileynj/fantasyfeudalismmobs/client/ForestBirdGeometry.java'
KINDS=[('ROBIN','Robin.bbmodel'),('BLUE_JAY','Blue Jay.bbmodel'),('GOLDFINCH','Goldfinch.bbmodel'),('CROW','Crow.bbmodel')]
PIVOTS={'body':[8,0,8],'head':[8,6.5,8],'left_wing':[6,6,8],'right_wing':[10,6,8],'left_leg':[6.5,2.5,9.3],'right_leg':[9.5,2.5,9.3],'tail':[8,5.5,13]}
def f(v):return f'{v:.6f}'.rstrip('0').rstrip('.')+'F' if '.' in f'{v:.6f}'.rstrip('0').rstrip('.') else f'{v:.0f}F'
def vec(v):return ','.join(f(x) for x in v)
def add(lines,part,e,name,material,row):
    pivot=PIVOTS[part];rotation=e.get('rotation',[0,0,0]);origin=e.get('origin',pivot) if any(rotation) else pivot
    a=e['from'];b=e['to'];box=[a[0]-origin[0],origin[1]-b[1],a[2]-origin[2],b[0]-a[0],b[1]-a[1],b[2]-a[2]]
    pose='PartPose.ZERO'
    if any(rotation):
        offset=[origin[0]-pivot[0],pivot[1]-origin[1],origin[2]-pivot[2]]
        rot=[-math.radians(rotation[0]),math.radians(rotation[1]),-math.radians(rotation[2])]
        pose='PartPose.offsetAndRotation('+vec(offset+rot)+')'
    u,v=material*32,row*32
    if row==1 and 'wing' in part:
        # Small wing sections otherwise sample a flat corner instead of the feather seams.
        v+=8
        if material==6:u+=4
    lines.append(f'        {part}.addOrReplaceChild("{name}",CubeListBuilder.create().texOffs({u},{v}).addBox({vec(box)}),{pose});')
def overlay(lines,part,name,box,mat,row):
    lines.append(f'        {part}.addOrReplaceChild("{name}",CubeListBuilder.create().texOffs({mat*32},{row*32}).addBox({vec(box)}),PartPose.ZERO);')
lines=['package net.itsrileynj.fantasyfeudalismmobs.client;','','import net.itsrileynj.fantasyfeudalismmobs.BirdKind;','import net.minecraft.client.model.geom.PartPose;','import net.minecraft.client.model.geom.builders.*;','','/** Generated by tools/import_bird_models.py from the supplied Blockbench sources. */','public final class ForestBirdGeometry {','    private ForestBirdGeometry() {}','    public static LayerDefinition layer(BirdKind kind) {','        var mesh=new MeshDefinition();','        var bird=mesh.getRoot().addOrReplaceChild("bird",CubeListBuilder.create(),PartPose.offset(0,24,0));']
for name,p in PIVOTS.items():
    offset=[p[0]-8,-p[1],p[2]-8]
    lines.append(f'        var {name}=bird.addOrReplaceChild("{name}",CubeListBuilder.create(),PartPose.offset({vec(offset)}));')
lines.append('        switch(kind) {')
manifest=[]
for row,(kind,filename) in enumerate(KINDS):
    source=SOURCES/filename;data=json.loads(source.read_text());manifest.append({'kind':kind,'source':filename,'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'cubes':len(data['elements'])})
    lines.append(f'        case {kind} -> {{')
    for i,e in enumerate(data['elements']):
        part='left_leg' if i in (0,2) else 'right_leg' if i in (1,3) else 'head' if i in (5,6) or (kind=='BLUE_JAY' and i==12) else 'tail' if i==7 else 'left_wing' if i==8 or (kind=='CROW' and i in (12,14)) else 'right_wing' if i==9 or (kind=='CROW' and i in (13,15)) else 'body'
        material=4 if i in (0,1,2,3,6) else 7 if i==7 else 2 if 'wing' in part else 0 if i in (4,5) else 1
        if kind=='GOLDFINCH' and i in (0,1,2,3):material=7
        if kind=='BLUE_JAY' and i in (10,11):material=3
        if i in (4,11) and kind!='CROW':
            split=3.6 if i==4 else 3.5
            for j,(lo,hi,mat) in enumerate([(e['from'][1],split,3),(split,e['to'][1],material)]):
                clone=dict(e);clone['from']=e['from'].copy();clone['to']=e['to'].copy();clone['from'][1]=lo;clone['to'][1]=hi
                add(lines,part,clone,f'cube_{i}_{j}',mat,row)
        elif i==5 and kind=='GOLDFINCH':
            # Color the original head's upper section as the reference's black crown.
            for j,(lo,hi,mat) in enumerate([(e['from'][1],9.6,0),(9.6,e['to'][1],5)]):
                clone=dict(e);clone['from']=e['from'].copy();clone['to']=e['to'].copy()
                clone['from'][1]=lo;clone['to'][1]=hi
                add(lines,part,clone,f'cube_{i}_{j}',mat,row)
        elif i==10 and kind=='BLUE_JAY':
            # Put the collar's color on the original chest cube without adding an overlapping box.
            for j,(lo,hi,mat) in enumerate([(e['from'][1],5.9,3),(5.9,e['to'][1],1)]):
                clone=dict(e);clone['from']=e['from'].copy();clone['to']=e['to'].copy()
                clone['from'][1]=lo;clone['to'][1]=hi
                add(lines,part,clone,f'cube_{i}_{j}',mat,row)
        elif i in (8,9) and kind in ('BLUE_JAY','GOLDFINCH'):

            # Partition, rather than reshape, the supplied wing cube for its reference-image bands.
            cuts=[(0,.7,2),(.7,1.15,6),(1.15,2,2),(2,2.45,6),(2.45,4,2)] if kind=='BLUE_JAY' else [(0,1,2),(1,1.6,6),(1.6,2.8,2),(2.8,4,0)]
            for j,(lo,hi,mat) in enumerate(cuts):
                clone=dict(e);clone['from']=e['from'].copy();clone['to']=e['to'].copy()
                if i==8:clone['from'][0]=2+lo;clone['to'][0]=2+hi
                else:clone['from'][0]=14-hi;clone['to'][0]=14-lo
                add(lines,part,clone,f'cube_{i}_{j}',mat,row)
        else:add(lines,part,e,f'cube_{i}',material,row)
    if kind=='BLUE_JAY':
        overlay(lines,'head','white_face',[-2,-3,-2.025,4,3,.025],3,row)
    elif kind=='ROBIN':
        overlay(lines,'head','left_cheek',[-2,-2.9,-2.025,.85,2.8,.025],6,row)
        overlay(lines,'head','right_cheek',[1.15,-2.9,-2.025,.85,2.8,.025],6,row)
        overlay(lines,'head','orange_face',[-1.15,-1.5,-2.03,2.3,1.5,.03],1,row)
    for name,x in [('left',-1.65),('right',1.05)]:overlay(lines,'head',name+'_front_eye',[x,-2.85,-2.065,.6,.75,.04],5,row)
    lines.append('        }')
lines+=['        }','        return LayerDefinition.create(mesh,256,128);','    }','}']
OUT.write_text('\n'.join(lines)+'\n')
(SOURCES/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Imported',sum(m['cubes'] for m in manifest),'original cubes across four species into',OUT)
